import { build } from 'esbuild'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const policyPath = process.env.HERMES_TURN_ROUTER_POLICY
let policy
if (policyPath) {
  policy = JSON.parse(await readFile(resolve(policyPath), 'utf8'))
  delete policy.$schema
  const { validatePolicy } = await import('../dist/router.js')
  validatePolicy(policy)
  console.log(`Embedding custom Desktop policy from ${resolve(policyPath)}`)
}

await build({
  entryPoints: ['integrations/hermes/desktop/plugin-entry.ts'],
  outfile: 'integrations/hermes/desktop/plugin.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  external: ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime'],
  minify: false,
  sourcemap: false,
  define: policy
    ? { __HERMES_TURN_ROUTER_POLICY__: JSON.stringify(policy) }
    : {},
  banner: { js: '// Generated by npm run build:plugin. Do not edit directly.' }
})
console.log('Built integrations/hermes/desktop/plugin.js')
